"""PostgreSQL connections and the small SQL compatibility boundary used by db.py."""

from __future__ import annotations

import os
import re
import threading
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

WORKSPACE_LOCK = 804629101  # One shared demo workspace, serialized writers.
_OWNER = None
_SQL_LOCK = threading.RLock()


def _open():
    # Session mode (port 5432) is required for worker advisory locks.
    conn = psycopg.connect(
        os.environ["DATABASE_URL"], row_factory=dict_row,
        connect_timeout=10, prepare_threshold=None,
    )
    conn.execute("SET search_path TO app_private")
    conn.commit()
    return conn


@contextmanager
def connect():
    """Writes use the exact session that owns the workspace lock.

    A lost lock connection is fatal to that operation; it cannot reconnect and
    overwrite work performed by a replacement worker. Threads serialize SQL.
    """
    if _OWNER is not None:
        with _SQL_LOCK, _OWNER.transaction():
            yield _OWNER
    else:
        with _open() as conn:
            yield conn


def parameters(sql: str) -> str:
    """Translate only parameter tokens, never SQL literals or user values."""
    parts = re.split(r"('(?:''|[^'])*')", sql)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r"(?<!:):([A-Za-z_]\w*)", r"%(\1)s", parts[i]).replace("?", "%s")
    return "".join(parts)


class Connection:
    """Keep the repository's SQL and dictionary rows shared across both databases."""

    def __init__(self):
        self.context = connect()
        self.conn = self.context.__enter__()

    def execute(self, sql, params=None):
        return self.conn.execute(parameters(sql), params)

    def __enter__(self):
        return self

    def __exit__(self, kind, value, tb):
        return self.context.__exit__(kind, value, tb)


@contextmanager
def writer_lock(*, transaction=False):
    """A live DB session owns the lock; a crash releases it automatically."""
    global _OWNER
    with _open() as conn:
        acquired = conn.execute("SELECT pg_try_advisory_lock(%s) AS ok", (WORKSPACE_LOCK,)).fetchone()["ok"]
        conn.commit()
        try:
            if acquired:
                if _OWNER is not None:
                    raise RuntimeError("Only one operation per process is supported")
                _OWNER = conn
            if acquired and transaction:
                with conn.transaction():
                    yield acquired
            else:
                yield acquired
        finally:
            _OWNER = None
            if acquired:
                if not conn.closed:
                    conn.execute("SELECT pg_advisory_unlock(%s)", (WORKSPACE_LOCK,))


def initialize():
    from app import db

    with connect() as conn:
        conn.execute("CREATE SCHEMA IF NOT EXISTS app_private")
        conn.execute("REVOKE ALL ON SCHEMA app_private FROM PUBLIC")
        conn.execute("SET search_path TO app_private")
        for schema in (db._SCHEMA, db._ROWS_SCHEMA, db._PENDING_SCHEMA):
            schema = schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            for statement in schema.split(";"):
                if statement.strip():
                    conn.execute(statement)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS batches (
                batch_id TEXT PRIMARY KEY, payload JSONB NOT NULL,
                updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS jobs (
                job_id TEXT PRIMARY KEY, batch_id TEXT NOT NULL,
                record_id TEXT, kind TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'queued',
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(), finished_at TIMESTAMPTZ,
                error TEXT
            )
        """)
        conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS active_batch_job ON jobs(batch_id) WHERE status IN ('queued','running')")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS artifacts (
                path TEXT PRIMARY KEY, object_key TEXT NOT NULL, sha256 TEXT NOT NULL,
                size BIGINT NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS uploads (
                upload_id TEXT PRIMARY KEY, object_key TEXT NOT NULL,
                filename TEXT NOT NULL, size BIGINT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(), batch_id TEXT,
                position INTEGER NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS garbage (
                object_key TEXT PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
        """)
        conn.execute("REVOKE ALL ON ALL TABLES IN SCHEMA app_private FROM PUBLIC")
        # Supabase's public API roles must not bypass the authenticated server.
        for role in ("anon", "authenticated"):
            if conn.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (role,)).fetchone():
                conn.execute(psycopg.sql.SQL("REVOKE ALL ON SCHEMA app_private FROM {}").format(psycopg.sql.Identifier(role)))


if __name__ == "__main__":
    initialize()
    print("Cloud schema initialized (no documents migrated).")
